CREATE TABLE IF NOT EXISTS walk_locations (
  id                    UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  district              TEXT        NOT NULL,
  city                  TEXT        NOT NULL DEFAULT 'Москва',
  park_name             TEXT        NOT NULL,
  meeting_point         TEXT        NOT NULL,    -- specific spot in the park
  address               TEXT,
  lat                   FLOAT,
  lon                   FLOAT,
  rain_backup_name      TEXT,                    -- nearby cafe if it rains
  rain_backup_address   TEXT,
  is_active             BOOLEAN     DEFAULT TRUE,
  created_at            TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_walk_locations_district ON walk_locations (district) WHERE is_active = TRUE;
